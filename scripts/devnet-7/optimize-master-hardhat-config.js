/**
 * Patch a master worktree hardhat-common.config.js for size-optimized compiles.
 * Required so master megapool / deposit pool / minipool contracts fit under the
 * 24 KiB EIP-170 limit on pre-Gloas Kurtosis (production deploys use optimized
 * artifacts; the monorepo default is optimizer: false for tests).
 *
 * Usage:
 *   node scripts/devnet-7/optimize-master-hardhat-config.js /path/to/.devnet-master/hardhat-common.config.js
 */
const fs = require('fs');

const target = process.argv[2];
if (!target || !fs.existsSync(target)) {
    console.error('Usage: node optimize-master-hardhat-config.js <hardhat-common.config.js>');
    process.exit(1);
}

const optimized = `require('dotenv').config();
require('@nomicfoundation/hardhat-ethers');

// Importing babel to be able to use ES6 imports
require('@babel/register')({
    presets: [
        ['@babel/preset-env', {
            'targets': {
                'node': '16',
            },
        }],
    ],
    only: [/test|scripts/],
    retainLines: true,
});
require('@babel/polyfill');

/** @type import('hardhat/config').HardhatUserConfig */
// Size-optimized for Kurtosis pre-Gloas deploy (EIP-170 24 KiB code size).
// Generated by scripts/devnet-7/optimize-master-hardhat-config.js — do not use for tests.
module.exports = {
    solidity: {
        compilers: [
            {
                version: '0.7.6',
                settings: {
                    optimizer: {
                        enabled: true,
                        runs: 1,
                    },
                },
            },
            {
                version: '0.8.30',
                settings: {
                    optimizer: {
                        enabled: true,
                        runs: 1,
                    },
                    viaIR: true,
                },
            },
        ],
    },
    networks: {},
    paths: {
        sources: './contracts',
        tests: './test',
        cache: './cache',
        artifacts: './artifacts',
    },
    mocha: {
        timeout: 0,
    },
};
`;

fs.writeFileSync(target, optimized, 'utf8');
console.log(`Wrote size-optimized hardhat config to ${target}`);
